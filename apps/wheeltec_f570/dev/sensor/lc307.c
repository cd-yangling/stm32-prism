static int lc307_ack(struct lc307 *s, unsigned char *fb)
{
	unsigned int deadline = tick_get() + 50u;
	unsigned int got = 0u;

	while (3u > got)
	{
		unsigned char c;

		if (0 == uart_poll_getc(s->io.dev->port, &c))
		{
			fb[got] = c;
			got++;
		}

		if (tick_expired(deadline))
		{
			return -ETIMEDOUT;
		}
	}

	if ((unsigned char)(fb[0] ^ fb[1]) != fb[2])
	{
		return -EIO;
	}

	if (0x00 != fb[1])
	{
		return -EIO;
	}

	return 0;
}

int lc307_init(struct lc307 *s)
{
	static const unsigned char step1[7] =
	{
		0xAA, 0xAB, 0x96, 0x26, 0xBC, 0x50, 0x5C,
	};
	unsigned char fb[3];
	unsigned int deadline = tick_get() + 1500u;
	unsigned int i;
	int r;

	(void)deframer_init(&s->io.dfr, s->io.dfr_cfg);

	while (!tick_expired(deadline))
	{
		unsigned char c;

		if (0 == uart_poll_getc(s->io.dev->port, &c))
		{
			if (0 < deframer_feed(&s->io.dfr, &c, 1u, 0u))
			{
				return strm_deframer_init(&s->io);
			}
		}
	}

	(void)uart_poll_write(s->io.dev->port, step1, sizeof(step1));
	r = lc307_ack(s, fb);

	if (0 != r)
	{
		return r;
	}

	for (i = 0u; i < sizeof(tab_bf3901); i += 2u)
	{
		unsigned char buf[5];

		buf[0] = 0xBB;
		buf[1] = 0xDC;
		buf[2] = tab_bf3901[i];
		buf[3] = tab_bf3901[i + 1u];
		buf[4] = (unsigned char)(buf[1] ^ buf[2] ^ buf[3]);

		(void)uart_poll_write(s->io.dev->port, buf, 5u);
		r = lc307_ack(s, fb);

		if (0 != r)
		{
			return r;
		}
	}

	{
		unsigned char close = 0xDD;

		(void)uart_poll_write(s->io.dev->port, &close, 1u);
	}

	return strm_deframer_init(&s->io);
}

void lc307_feed(struct lc307 *s)
{
	strm_deframer_feed(&s->io);
}

const struct lc307_rec *lc307_peek(struct lc307 *s)
{
	const struct deframer_rec *fr = strm_deframer_peek(&s->io);

	if (NULL == fr)
	{
		return NULL;
	}

	s->rec.flowx = (short)get_le16(&fr->buf[2]);
	s->rec.flowy = (short)get_le16(&fr->buf[4]);
	s->rec.dt_us = get_le16(&fr->buf[6]);
	s->rec.valid = fr->buf[10];
	s->rec.ver = fr->buf[11];
	s->rec.ts = fr->ts;

	return &s->rec;
}

void lc307_advance(struct lc307 *s)
{
	strm_deframer_advance(&s->io);
}

float lc307_flow_rad(short flowv, unsigned short dt_us)
{
	if (0u == dt_us)
	{
		return 0.0f;
	}

	return (float)flowv * 100.0f / (float)dt_us;
}

