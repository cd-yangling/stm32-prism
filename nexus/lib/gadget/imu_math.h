/**
 *	纯整数 IMU 数学实现: CORDIC atan2, LUT atan2, 整数 sqrt (考虑给无硬件FPU使用)
 *
 * ============================================================
 * 角度单位约定(本库统一使用 "百分之一度" = centidegree)
 *   1 centidegree = 0.01度
 *   例: 4500 = 45.00度,  -9000 = -90.00度,  18000 = 180.00度
 * ============================================================
 *         1: 惯性测量单元的数据结算
 *         2: 互补滤波姿态数据的融合
 *         3: mahony  姿态数据的融合
 *
 *  CORDIC atan2 与 LUT atan2 可以任意选择一个来使用
 *
 * 所有函数: 无 float, 无 double, 无 FPU 指令
 *
 * CORDIC: 额外无除法 (只有加减法 + 算术移位)
 *    LUT: 存在2次除法
 *
 * LUT 和 CORDIC 的本质区别:
 *      LUT: 用 "空间换时间" (查表方式), 但无法彻底消除除法
 *   CORDIC: 用 "时间换空间" (迭代计算), 彻底消除除法和乘法
 */

#ifndef __NEXUS_LIB_GADGET_IMU_MATH_HEADER__
#define __NEXUS_LIB_GADGET_IMU_MATH_HEADER__

#include <stdint.h>

/*
 * ============================================================
 *  角度常量 (单位: centidegree, 即 0.01度)
 * ============================================================
*/
#define ANGLE_0DEG       (0)
#define ANGLE_45DEG      (4500)
#define ANGLE_90DEG      (9000)
#define ANGLE_180DEG     (18000)
#define ANGLE_360DEG     (36000)

/* ============================================================
 *  CORDIC atan2
 *  完全无除法,无乘法,无浮点
 * ============================================================
 *
 * @param y   y 分量 (加速度计原始值, int16_t 范围即可)
 * @param x   x 分量
 * @return    atan2(y, x) 单位 centidegree
 *
 * 精度: 14次迭代 -> 误差 < 0.01度
 *
 * 同时计算幅值:
 *   cordic_atan2_with_mag() 还输出 (1/K) * sqrt(x^2 + y^2)
 *   其中 1/K ~= 1.6468 (伪旋转累积增益, 放大)
 *   注意: 该幅值含 1/K 放大, 不可直接当第二次 atan2 的 x 用
 *         (y 分子未同缩放, 角度会偏); 需无缩放幅值请用 isqrt32
 *   输入范围按 int16 设计; int32 大值会在迭代中间值溢出
 */
int32_t cordic_atan2(int32_t y, int32_t x);

/**
 * @brief CORDIC atan2 并同时输出缩放幅值
 *        magnitude_out = (1/CORDIC_K) x sqrt(y^2 + x^2), 其中 1/CORDIC_K 约等于 1.6468 (放大)
 *        传 NULL 则不输出幅值
 */
int32_t cordic_atan2_with_mag(int32_t y, int32_t x, int32_t *magnitude_out);

/* ============================================================
 *  CORDIC sin / cos (旋转模式 Rotation Mode)
 *  完全无除法, 无浮点, 纯移位与加减
 * ============================================================
 *
 * @param angle_centideg  输入角度, 单位 centidegree (0.01度), 范围 [-18000, 18000]
 * @param sin_q14         输出 sin 值的 Q14 定点数指针 (1.0 = 16384), 传 NULL 可不接收
 * @param cos_q14         输出 cos 值的 Q14 定点数指针 (1.0 = 16384), 传 NULL 可不接收
 *
 * Q14 格式:
 *   16384 = 1.0, 8192 = 0.5, 0 = 0.0, -16384 = -1.0
 *   精度: 14次迭代, 误差 < 0.001 (Q14 对应 < 15 LSB)
 *
 * 用途: 四元数姿态解算初始化 (欧拉角 -> 四元数),三维坐标旋转变换
 */
void cordic_sincos(int32_t angle_centideg, int32_t *sin_q14, int32_t *cos_q14);

/* ============================================================
 *  LUT atan2 (查表法, 需要 1~2 次整数除法)
 * ============================================================
 *
 * @param y  y 分量
 * @param x  x 分量
 * @return   atan2(y, x) 单位 centidegree
 *
 * 精度: 33点 LUT + 线性插值 -> 误差 < 0.06度
 * 代价: 内部需要 2 次整数除法 (求比值 + 插值)
 *
 * 与 CORDIC 比较:
 *   CORDIC: 0 除法, 14次加减+移位, 精度约0.01度
 *   LUT   : 2 除法, 1次查表+乘法, 精度约0.06度 (取决于表大小)
 *
 * 备注说明
 *   默认路径中间量 int64, 任意 int32 输入安全(64 位除法走 __aeabi_ldivmod)
 *   定义 LUT_ATAN2_INPUT_16BIT 走纯 32 位快路径(无 64 位除法),
 *   调用方承诺 |x| 与 |y| <= 32767 (int16 范围)
 */
int32_t lut_atan2(int32_t y, int32_t x);

/* ============================================================
 *  整数平方根 (无除法, 无浮点)
 * ============================================================
 *
 * 算法: 逐位确定法
 * 成本: 16次循环, 每次仅移位+比较+减法
 * 精度: 完全精确 (floor(sqrt(n)) 的精确整数结果)
 *
 * 用途: pitch 角计算需要 sqrt(ay^2 + az^2)
 *       对于平衡小车(单轴), 无需调用此函数
 *       对于四轴飞行器(双轴), 必须使用此函数
 *
 * 备注: 若使用 CORDIC 的幅值输出(带K缩放), 则无需显式调用 isqrt32
 */
uint32_t isqrt32(uint32_t n);

#endif /* __NEXUS_LIB_GADGET_IMU_MATH_HEADER__ */
